/**
 * Нормализация телефона для сравнения номеров.
 * - оставляем только цифры (устойчиво к '+', пробелам, дефисам, скобкам);
 * - для 11-значных номеров региона +7 (РФ/КЗ) ведущую 8 приводим к 7,
 *   чтобы локальный формат 8-708-... совпадал с международным +7 708-...
 *
 * Возвращает строку из цифр в каноничном виде.
 */
export function normalizePhone(input: string): string {
  let d = (input || '').replace(/\D/g, '');
  if (d.length === 11 && d.startsWith('8')) {
    d = '7' + d.slice(1);
  }
  return d;
}
