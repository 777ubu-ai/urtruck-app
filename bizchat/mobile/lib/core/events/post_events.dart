import 'package:flutter/foundation.dart';

/// Глобальное событие «опубликован новый пост».
///
/// Нужно, потому что форма публикации больше не живёт вкладкой в нижнем меню:
/// её открывают «плюсом» из профиля, поверх текущего экрана. Лента при этом
/// остаётся во вкладке рядом и сама о публикации не узнает — а пользователь
/// ждёт увидеть свой товар первым.
///
/// MainShell слушает это уведомление и пересоздаёт ленту, профиль — обновляет
/// сетку товаров. Одно событие вместо колбэков через несколько слоёв.
class PostEvents extends ChangeNotifier {
  PostEvents._();
  static final PostEvents instance = PostEvents._();

  void notifyCreated() => notifyListeners();
}
