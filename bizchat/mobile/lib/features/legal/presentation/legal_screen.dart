import 'package:flutter/material.dart';

/// Универсальный экран для юридических документов (Terms of Service,
/// Privacy Policy). Отображает содержимое через Markdown-like форматирование
/// в виде простых Text виджетов (без зависимости от markdown пакета).
class LegalScreen extends StatelessWidget {
  const LegalScreen({
    super.key,
    required this.title,
    required this.sections,
  });

  final String title;

  /// Список секций: каждая — заголовок + список параграфов.
  final List<LegalSection> sections;

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    return Scaffold(
      appBar: AppBar(title: Text(title)),
      body: ListView.builder(
        padding: const EdgeInsets.all(20),
        itemCount: sections.length,
        itemBuilder: (_, i) {
          final s = sections[i];
          return Padding(
            padding: const EdgeInsets.only(bottom: 24),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  '${i + 1}. ${s.heading}',
                  style: Theme.of(context).textTheme.titleMedium?.copyWith(
                        fontWeight: FontWeight.w700,
                      ),
                ),
                const SizedBox(height: 8),
                ...s.paragraphs.map(
                  (p) => Padding(
                    padding: const EdgeInsets.only(bottom: 6),
                    child: Text(
                      p,
                      style: Theme.of(context).textTheme.bodyMedium?.copyWith(
                            color: scheme.onSurfaceVariant,
                            height: 1.6,
                          ),
                    ),
                  ),
                ),
              ],
            ),
          );
        },
      ),
    );
  }
}

class LegalSection {
  const LegalSection({required this.heading, required this.paragraphs});
  final String heading;
  final List<String> paragraphs;
}

