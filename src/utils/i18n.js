// PR-C2 (Task C auto-detect): expo-localization выдаёт надёжный locale
// на iOS/Android — лучше чем NativeModules.SettingsManager.AppleLocale
// (deprecated в новых RN). Лоадим лениво чтобы web-bundle не тащил
// нативный модуль.
let _Localization;
function getLocalization() {
  if (_Localization !== undefined) return _Localization;
  try { _Localization = require('expo-localization'); } catch { _Localization = null; }
  return _Localization;
}

const listeners = new Set();
const KEY = 'ur_lang';

// Алиасы: системный код → наш код. Поддерживаем только 4 языка:
// RU / EN / KK (Kazakh, ISO 639-1) / ZH (Chinese, ISO 639-1).
//
// Stage 7 standardised the codes to ISO. Earlier the storage might
// have written `'KZ'` (country code, not language) or `'CN'` (also
// country code) into `ur_lang`; the loader below now redirects those
// legacy values to the proper language code so users don't lose
// their choice on upgrade.
const LANG_ALIAS = {
  ru: 'RU', rus: 'RU',
  en: 'EN', eng: 'EN',
  kk: 'KK', kaz: 'KK', 'kk-kz': 'KK',
  zh: 'ZH', 'zh-cn': 'ZH', 'zh-hans': 'ZH', 'zh-hant': 'ZH', 'zh-tw': 'ZH',
};

// Legacy persisted-value fixups. Stage 5 narrowed the set to four
// languages and renamed two of them in Stage 7 (KZ→KK, CN→ZH).
// Anything else falls through to system detect / RU.
const LEGACY_LANG_FIX = {
  KZ: 'KK',
  CN: 'ZH',
};

// Sync detect at module load — best effort before async storage
// PR-C2: default fallback на 'EN' вместо 'RU' — для пользователей с
// неподдерживаемым языком устройства это даёт более универсальный first-run
// experience. RU/KK/ZH юзеры всё равно попадают в свою локаль через alias.
let currentLang = (() => {
  try {
    let code = '';
    if (typeof navigator !== 'undefined' && navigator.language) {
      code = navigator.language.toLowerCase();
    }
    if (!code) return 'EN';
    const base = code.split('-')[0];
    if (LANG_ALIAS[code]) return LANG_ALIAS[code];
    if (LANG_ALIAS[base]) return LANG_ALIAS[base];
    return 'EN'; // unsupported → EN
  } catch { return 'EN'; }
})();

function detectSystemLang() {
  let code;
  try {
    // PR-C2: предпочитаем expo-localization (Localization.getLocales() в
    // SDK 52, или Localization.locale в legacy). Это работает на новых
    // iOS / Android без NativeModules deprecation warnings.
    if (Platform.OS !== 'web') {
      const Loc = getLocalization();
      if (Loc) {
        try {
          // SDK 52 API: getLocales() возвращает array of { languageTag, … }
          const locales = Loc.getLocales?.();
          if (Array.isArray(locales) && locales.length && locales[0].languageTag) {
            code = String(locales[0].languageTag).toLowerCase();
          }
        } catch {}
        if (!code && Loc.locale) {
          code = String(Loc.locale).toLowerCase().replace('_', '-');
        }
      }
    }
    if (!code) {
      if (Platform.OS === 'web' && typeof navigator !== 'undefined') {
        code = (navigator.language || navigator.userLanguage || '').toLowerCase();
      } else {
        const locale =
          NativeModules.SettingsManager?.settings?.AppleLocale ||
          NativeModules.SettingsManager?.settings?.AppleLanguages?.[0] ||
          NativeModules.I18nManager?.localeIdentifier ||
          '';
        code = locale.toLowerCase().replace('_', '-');
      }
    }
  } catch {
    code = '';
  }
  if (!code) return null;
  // пробуем полный код, потом основу
  if (LANG_ALIAS[code]) return LANG_ALIAS[code];
  const base = code.split('-')[0];
  if (LANG_ALIAS[base]) return LANG_ALIAS[base];
  return null;
}

// Load saved language on start; если не выбран — авто из системы.
// PR-C2: если detect ничего не нашёл — устанавливаем EN (универсальный
// fallback для приграничных пользователей с экзотическими locale).
(async () => {
  let saved = await storage.get(KEY);
  // Legacy fix-up: rewrite `KZ` → `KK`, `CN` → `ZH` for users
  // upgrading from a Stage 5 build.
  if (saved && LEGACY_LANG_FIX[saved]) {
    saved = LEGACY_LANG_FIX[saved];
    storage.set(KEY, saved);
  }
  if (saved && translations[saved]) {
    currentLang = saved;
  } else {
    const sys = detectSystemLang();
    if (sys && translations[sys]) {
      currentLang = sys;
      storage.set(KEY, sys); // сохраняем выбор авто
    } else if (!translations[currentLang]) {
      currentLang = 'EN';
      storage.set(KEY, 'EN');
    }
  }
  syncDocumentLanguage(currentLang);
  listeners.forEach(cb => cb(currentLang));
})();

const HTML_LANG = { RU: 'ru', KK: 'kk', ZH: 'zh-CN', EN: 'en' };

const syncDocumentLanguage = (lang) => {
  // The browser translator was appearing above the Chinese UI because the
  // document stayed marked as English. Native builds have no `document`.
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = HTML_LANG[lang] || 'en';
  }
};

export const setLanguage = (lang) => {
  currentLang = translations[lang] ? lang : 'EN';
  storage.set(KEY, currentLang);
  syncDocumentLanguage(currentLang);
  listeners.forEach(cb => cb(currentLang));
};

export const getLanguage = () => currentLang;

export const subscribeToLanguage = (cb) => {
  listeners.add(cb);
  return () => listeners.delete(cb);
};

export const t = (key) => {
  const lang = translations[currentLang];
  if (lang && lang[key]) return lang[key];
  return translations.RU[key] || key;
};

// Склонение для русского: 1 ставка, 2 ставки, 5 ставок
function pluralRu(n, one, few, many) {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs >= 11 && abs <= 14) return many;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

export const formatBids = (count) => {
  const n = count || 0;
  // Единая терминология: «предложение» (как в колоколе «Новое предложение» и
  // вкладке «Предложения»), а не «ставка» — одно слово во всём флоу сделки.
  if (currentLang === 'RU' || currentLang === 'KK' || currentLang === 'KG') {
    return `${n} ${pluralRu(n, 'предложение', 'предложения', 'предложений')}`;
  }
  return `${n} ${t('bids')}`;
};

