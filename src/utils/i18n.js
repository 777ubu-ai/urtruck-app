import { storage } from './storage';
import { Platform, NativeModules } from 'react-native';

const listeners = new Set();
const KEY = 'ur_lang';

// Алиасы: системный код → наш код. Поддерживаем только 4 языка:
// RU / EN / KK (Kazakh, ISO 639-1) / ZH (Chinese, ISO 639-1).
//
// Stage 7 standardised the codes to ISO. Earlier the storage might
// have written `'KZ'` (country code, not language) or `'CN'` (also
// country code) into `ur_lang`; the loader below now redirects those
// legacy values to the proper language code so users don't lose
// their choice on upgrade.
const LANG_ALIAS = {
  ru: 'RU', rus: 'RU',
  en: 'EN', eng: 'EN',
  kk: 'KK', kaz: 'KK', 'kk-kz': 'KK',
  zh: 'ZH', 'zh-cn': 'ZH', 'zh-hans': 'ZH', 'zh-hant': 'ZH', 'zh-tw': 'ZH',
};

// Legacy persisted-value fixups. Stage 5 narrowed the set to four
// languages and renamed two of them in Stage 7 (KZ→KK, CN→ZH).
// Anything else falls through to system detect / RU.
const LEGACY_LANG_FIX = {
  KZ: 'KK',
  CN: 'ZH',
};

// Sync detect at module load — best effort before async storage
let currentLang = (() => {
  try {
    let code = '';
    if (typeof navigator !== 'undefined' && navigator.language) {
      code = navigator.language.toLowerCase();
    }
    if (!code) return 'RU';
    const base = code.split('-')[0];
    if (LANG_ALIAS[code]) return LANG_ALIAS[code];
    if (LANG_ALIAS[base]) return LANG_ALIAS[base];
    return 'RU'; // unsupported → RU
  } catch { return 'RU'; }
})();

function detectSystemLang() {
  let code;
  try {
    if (Platform.OS === 'web' && typeof navigator !== 'undefined') {
      code = (navigator.language || navigator.userLanguage || '').toLowerCase();
    } else {
      const locale =
        NativeModules.SettingsManager?.settings?.AppleLocale ||
        NativeModules.SettingsManager?.settings?.AppleLanguages?.[0] ||
        NativeModules.I18nManager?.localeIdentifier ||
        '';
      code = locale.toLowerCase().replace('_', '-');
    }
  } catch {
    code = '';
  }
  if (!code) return null;
  // пробуем полный код, потом основу
  if (LANG_ALIAS[code]) return LANG_ALIAS[code];
  const base = code.split('-')[0];
  if (LANG_ALIAS[base]) return LANG_ALIAS[base];
  return null;
}

// Load saved language on start; если не выбран — авто из системы
(async () => {
  let saved = await storage.get(KEY);
  // Legacy fix-up: rewrite `KZ` → `KK`, `CN` → `ZH` for users
  // upgrading from a Stage 5 build.
  if (saved && LEGACY_LANG_FIX[saved]) {
    saved = LEGACY_LANG_FIX[saved];
    storage.set(KEY, saved);
  }
  if (saved && translations[saved]) {
    currentLang = saved;
  } else {
    const sys = detectSystemLang();
    if (sys && translations[sys]) {
      currentLang = sys;
      storage.set(KEY, sys); // сохраняем выбор авто
    }
  }
  listeners.forEach(cb => cb(currentLang));
})();

export const setLanguage = (lang) => {
  currentLang = lang;
  storage.set(KEY, lang);
  listeners.forEach(cb => cb(lang));
};

export const getLanguage = () => currentLang;

export const subscribeToLanguage = (cb) => {
  listeners.add(cb);
  return () => listeners.delete(cb);
};

export const t = (key) => {
  const lang = translations[currentLang];
  if (lang && lang[key]) return lang[key];
  return translations.RU[key] || key;
};

// Склонение для русского: 1 ставка, 2 ставки, 5 ставок
function pluralRu(n, one, few, many) {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs >= 11 && abs <= 14) return many;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

export const formatBids = (count) => {
  const n = count || 0;
  if (currentLang === 'RU' || currentLang === 'KK' || currentLang === 'KG') {
    return `${n} ${pluralRu(n, 'ставка', 'ставки', 'ставок')}`;
  }
  return `${n} ${t('bids')}`;
};

export const formatStatus = (status) => {
  const key = `status_${status}`;
  const val = t(key);
  return val !== key ? val : t('status_unknown');
};

export const formatTruckType = (type) => {
  if (!type) return t('cargo_type_unknown');
  const val = t(type);
  return val !== type ? val : type;
};

export const formatCargoType = (type) => {
  if (!type) return t('cargo_type_unknown');
  const val = t(type);
  return val !== type ? val : type;
};

